/**
 * @brief The 7 row bitmasks of a character (lowercase maps to uppercase,
 *        unknown characters render blank).
 */
const unsigned char *OkFont::glyphRows(char c) {
  static const unsigned char BLANK[7] = {0, 0, 0, 0, 0, 0, 0};
  if (c >= 'a' && c <= 'z') {
    c = static_cast<char>(c - 'a' + 'A');
  }
  if (c >= '0' && c <= '9') {
    return DIGIT_FONT[c - '0'];
  }
  if (c >= 'A' && c <= 'Z') {
    return LETTER_FONT[c - 'A'];
  }
  if (c >= ' ' && c <= '/') {
    return PUNCT_32_47[c - ' '];
  }
  if (c >= ':' && c <= '@') {
    return PUNCT_58_64[c - ':'];
  }
  if (c >= '[' && c <= '`') {
    return PUNCT_91_96[c - '['];
  }
  if (c >= '{' && c <= '~') {
    return PUNCT_123_126[c - '{'];
  }
  return BLANK;
}

/**
 * @brief Rasterize a string to an RGBA texture: `scale` texture pixels per
 *        font pixel, 1 font pixel of margin around the text. The texture
 *        is registered in the texture handler under `name`.
 */
OkTexture *OkFont::bake(const std::string &name, const std::string &text,
                        int scale, const unsigned char fg[4],
                        const unsigned char bg[4]) {
  int nd = static_cast<int>(text.size());
  int fw = nd * ADVANCE + 1;  // glyphs + 1px gap each, 1px left margin
  int fh = GLYPH_H + 2;       // 1px margin top and bottom
  int w  = fw * scale;
  int h  = fh * scale;

  std::vector<unsigned char> rgba(static_cast<std::size_t>(w) * h * 4);
  for (int py = 0; py < h; py++) {
    // GL textures load bottom-up: sample the font from the top row.
    int fy = (h - 1 - py) / scale - 1;
    for (int px = 0; px < w; px++) {
      int  fx = px / scale - 1;
      bool on = false;
      if (fy >= 0 && fy < GLYPH_H && fx >= 0) {
        int di  = fx / ADVANCE;
        int col = fx % ADVANCE;
        if (di < nd && col < GLYPH_W) {
          const unsigned char *rows = glyphRows(text[static_cast<std::size_t>(di)]);
          on = ((rows[fy] >> (GLYPH_W - 1 - col)) & 1) != 0;
        }
      }
      const unsigned char *src = on ? fg : bg;
      std::size_t          o   = (static_cast<std::size_t>(py) * w + px) * 4;
      rgba[o]                  = src[0];
      rgba[o + 1]              = src[1];
      rgba[o + 2]              = src[2];
      rgba[o + 3]              = src[3];
    }
  }
  return OkTextureHandler::getInstance()->createTextureFromRawData(
      name, rgba.data(), w, h, 4);
}

/**
 * @brief The shared glyph atlas: ASCII 32..126 in a 16x6 cell grid, white
 *        glyphs on a transparent background, one texture pixel per font
 *        pixel (nearest sampling keeps it crisp at any element size).
 *        Built once and cached in the texture handler.
 */
OkTexture *OkFont::atlas() {
  static const std::string ATLAS_NAME = "okfont_atlas";
  OkTexture *cached = OkTextureHandler::getInstance()->getTexture(ATLAS_NAME);
  if (cached != nullptr) {
    return cached;
  }

  int w = ATLAS_COLS * ADVANCE;
  int h = ATLAS_ROWS * (GLYPH_H + 1);

  std::vector<unsigned char> rgba(static_cast<std::size_t>(w) * h * 4, 0);
  for (int ci = 0; ci < ATLAS_COLS * ATLAS_ROWS; ci++) {
    char c = static_cast<char>(' ' + ci);
    if (c > '~') {
      break;
    }
    const unsigned char *rows  = glyphRows(c);
    int                  cellX = (ci % ATLAS_COLS) * ADVANCE;
    int                  cellY = (ci / ATLAS_COLS) * (GLYPH_H + 1);
    for (int fy = 0; fy < GLYPH_H; fy++) {
      for (int col = 0; col < GLYPH_W; col++) {
        if (((rows[fy] >> (GLYPH_W - 1 - col)) & 1) == 0) {
          continue;
        }
        // Store bottom-up (GL convention): row 0 of the glyph is its top.
        int         px = cellX + col;
        int         py = h - 1 - (cellY + fy);
        std::size_t o  = (static_cast<std::size_t>(py) * w + px) * 4;
        rgba[o]        = 255;
        rgba[o + 1]    = 255;
        rgba[o + 2]    = 255;
        rgba[o + 3]    = 255;
      }
    }
  }
  OkTexture *tex = OkTextureHandler::getInstance()->createTextureFromRawData(
      ATLAS_NAME, rgba.data(), w, h, 4);
  if (tex != nullptr) {
    tex->setNearestFiltering();
  }
  return tex;
}

/**
 * @brief UV rectangle of a character's glyph cell inside atlas()
 *        (u0,v0 = bottom-left corner, GL convention).
 */
void OkFont::glyphUV(char c, float &u0, float &v0, float &u1, float &v1) {
  if (c >= 'a' && c <= 'z') {
    c = static_cast<char>(c - 'a' + 'A');
  }
  int ci = (c >= ' ' && c <= '~') ? (c - ' ') : 0;

  int   cellX = (ci % ATLAS_COLS) * ADVANCE;
  int   cellY = (ci / ATLAS_COLS) * (GLYPH_H + 1);
  float w     = static_cast<float>(ATLAS_COLS * ADVANCE);
  float h     = static_cast<float>(ATLAS_ROWS * (GLYPH_H + 1));

  u0 = static_cast<float>(cellX) / w;
  u1 = static_cast<float>(cellX + GLYPH_W) / w;
  // Atlas rows are stored top-down but the texture is bottom-up.
  v1 = (h - static_cast<float>(cellY)) / h;
  v0 = (h - static_cast<float>(cellY + GLYPH_H)) / h;
}
